"""
Passerelle Industrielle CalculiX CrunchiX (ccx) pour Calcul FEA Haute Performance (Pillar 7).
Équivalent professionnel du module FEM de FreeCAD 1.0.
Génère les fichiers de jeu de données (*.inp) au format Abaqus / CalculiX :
- Cartes de nœuds (*NODE) et d'éléments tétraédriques volumiques (*ELEMENT, TYPE=C3D4 / C3D10)
- Ensembles de nœuds (*NSET) et d'éléments (*ELSET)
- Lois de comportement matériau élastique linéaire (*MATERIAL, *ELASTIC)
- Conditions limites d'encastrement (*BOUNDARY) et cas de charge ponctuelle ou répartie (*CLOAD, *DLOAD)
- Cartes de calcul statique (*STEP, *STATIC) et requêtes d'export de contraintes (*EL FILE, S) et déplacements (*NODE FILE, U).
Comprend également un parseur de fichiers de résultats CalculiX (*.frd / format tabulaire).
Architecture fortement typée.
"""

from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum
from typing import List, Tuple, Dict, Optional
import os
import math

from src.core.types import Vector3D


class FeaElementType(str, Enum):
    """Types d'éléments finis volumiques supportés par CalculiX."""
    C3D4 = "C3D4"    # Tétraèdre linéaire à 4 nœuds
    C3D10 = "C3D10"  # Tétraèdre quadratique à 10 nœuds (haute précision industrielle)


@dataclass
class FeaMaterial:
    """Propriétés mécaniques d'un matériau pour le solveur CalculiX."""
    name: str = "Structural_Steel"
    young_modulus_mpa: float = 210000.0   # Module d'Young en MPa (N/mm²)
    poisson_ratio: float = 0.30           # Coefficient de Poisson nu
    density_kg_m3: float = 7850.0         # Masse volumique (kg/m³)


@dataclass
class NodalForce:
    """Force nodale concentrée (*CLOAD)."""
    node_id: int
    direction_dof: int  # 1 = X, 2 = Y, 3 = Z
    magnitude_n: float


@dataclass
class CalculixSimulationDeck:
    """
    Gestionnaire et générateur de jeu de données d'entrée (*.inp) pour CalculiX ccx.
    """
    job_name: str
    material: FeaMaterial
    element_type: FeaElementType = FeaElementType.C3D4
    nodes: Dict[int, Vector3D] = field(default_factory=dict)
    elements: Dict[int, List[int]] = field(default_factory=dict)
    fixed_node_ids: List[int] = field(default_factory=list)
    nodal_forces: List[NodalForce] = field(default_factory=list)

    def add_node(self, node_id: int, pos: Vector3D) -> None:
        """Ajoute un nœud géométrique avec ses coordonnées en millimètres."""
        self.nodes[node_id] = pos

    def add_tetrahedron(self, elem_id: int, node_ids: List[int]) -> None:
        """Ajoute un élément tétraédrique volumique."""
        self.elements[elem_id] = list(node_ids)

    def fix_node(self, node_id: int) -> None:
        """Bloque les 3 degrés de liberté de translation du nœud (Encastrement)."""
        if node_id not in self.fixed_node_ids:
            self.fixed_node_ids.append(node_id)

    def apply_load(self, node_id: int, direction_dof: int, magnitude_n: float) -> None:
        """Applique une charge concentrée sur un degré de liberté (1=Fx, 2=Fy, 3=Fz)."""
        self.nodal_forces.append(NodalForce(
            node_id=node_id,
            direction_dof=direction_dof,
            magnitude_n=magnitude_n
        ))

    def generate_inp_deck(self) -> str:
        """
        Génère la syntaxe complète du fichier de commande *.inp standard pour le solveur ccx.
        """
        lines: List[str] = [
            f"** ----------------------------------------------------",
            f"** CALCULIX INPUT DECK GENERATED BY CAD STUDIO INDUSTRIAL",
            f"** JOB: {self.job_name}",
            f"** ----------------------------------------------------",
            f"*HEADING",
            f"CAD Studio Linear Elastic Static Analysis - {self.job_name}",
            f"*NODE"
        ]

        # 1. Écriture des nœuds
        for n_id, pos in sorted(self.nodes.items()):
            lines.append(f"{n_id}, {pos.x:.6f}, {pos.y:.6f}, {pos.z:.6f}")

        # 2. Écriture des éléments finis
        lines.append(f"*ELEMENT, TYPE={self.element_type.value}, ELSET=EALL")
        for e_id, n_list in sorted(self.elements.items()):
            nodes_str = ", ".join(str(n) for n in n_list)
            lines.append(f"{e_id}, {nodes_str}")

        # 3. Ensembles de nœuds encastrés (*NSET)
        if self.fixed_node_ids:
            lines.append("*NSET, NSET=NFIXED")
            # Grouper par paquets de 10
            for i in range(0, len(self.fixed_node_ids), 10):
                batch = self.fixed_node_ids[i:i + 10]
                lines.append(", ".join(str(n) for n in batch))

        # 4. Définition du matériau et propriétés de section
        mat_name = self.material.name.upper()
        lines.append(f"*MATERIAL, NAME={mat_name}")
        lines.append("*ELASTIC")
        lines.append(f"{self.material.young_modulus_mpa:.2f}, {self.material.poisson_ratio:.4f}")
        lines.append(f"*SOLID SECTION, ELSET=EALL, MATERIAL={mat_name}")

        # 5. Conditions limites (*BOUNDARY)
        if self.fixed_node_ids:
            lines.append("*BOUNDARY")
            lines.append("NFIXED, 1, 3, 0.0")

        # 6. Pas de calcul statique (*STEP)
        lines.append("*STEP")
        lines.append("*STATIC")

        # Charges nodales (*CLOAD)
        if self.nodal_forces:
            lines.append("*CLOAD")
            for f in self.nodal_forces:
                lines.append(f"{f.node_id}, {f.direction_dof}, {f.magnitude_n:.4f}")

        # Requêtes de sortie des champs de résultats (Déplacement U et Contrainte S)
        lines.append("*NODE FILE")
        lines.append("U")
        lines.append("*EL FILE")
        lines.append("S")
        lines.append("*END STEP")

        return "\n".join(lines) + "\n"

    def write_to_file(self, filepath: str) -> None:
        """Écrit le fichier .inp sur disque."""
        deck_content = self.generate_inp_deck()
        os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(deck_content)


@dataclass
class FeaNodalResult:
    """Résultat nodal après résolution par CalculiX."""
    node_id: int
    displacement: Vector3D
    von_mises_stress_mpa: float


class CalculixResultParser:
    """
    Parseur des résultats produits par CalculiX (.frd ou .dat tabulaire).
    """

    def parse_nodal_displacements(self, result_text: str) -> Dict[int, Vector3D]:
        """
        Extrait les vecteurs déplacements (Ux, Uy, Uz) par ID de nœud.
        Gère les blocs CalculiX U standard.
        """
        results: Dict[int, Vector3D] = {}
        in_u_block = False

        for line in result_text.splitlines():
            line_str = line.strip()
            if "DISPLACEMENTS" in line_str.upper() or line_str.startswith("-4  DISP"):
                in_u_block = True
                continue
            if in_u_block:
                if line_str.startswith("-3") or line_str.startswith("-1"):
                    # Fin du bloc de résultats
                    in_u_block = False
                    continue
                parts = line_str.split()
                if len(parts) >= 4:
                    try:
                        n_id = int(parts[0])
                        ux = float(parts[1])
                        uy = float(parts[2])
                        uz = float(parts[3])
                        results[n_id] = Vector3D(ux, uy, uz)
                    except ValueError:
                        continue
        return results

    @staticmethod
    def _compute_von_mises_from_tensor(parts: List[str]) -> float:
        """Calcule la contrainte équivalente de von Mises à partir des 6 composantes du tenseur."""
        sxx = float(parts[1])
        syy = float(parts[2])
        szz = float(parts[3])
        sxy = float(parts[4])
        syz = float(parts[5])
        szx = float(parts[6])
        diff_sq = (sxx - syy) ** 2 + (syy - szz) ** 2 + (szz - sxx) ** 2
        shear_sq = 6.0 * (sxy ** 2 + syz ** 2 + szx ** 2)
        return math.sqrt(0.5 * (diff_sq + shear_sq))

    @classmethod
    def _parse_single_stress_line(cls, line_str: str) -> Optional[Tuple[int, float]]:
        """Parse une ligne unique de résultat de contraintes nodales CalculiX."""
        parts = line_str.split()
        if len(parts) < 2:
            return None
        try:
            n_id = int(parts[0])
            if len(parts) >= 7:
                vm = cls._compute_von_mises_from_tensor(parts)
            else:
                vm = float(parts[1])
            return n_id, vm
        except ValueError:
            return None

    def parse_nodal_stresses(self, result_text: str) -> Dict[int, float]:
        """
        Extrait les contraintes équivalentes de von Mises en MPa par ID de nœud.
        Gère les blocs STRESS / -4 STRESS avec tenseur complet ou scalaire direct.
        """
        results: Dict[int, float] = {}
        in_stress_block = False

        for line in result_text.splitlines():
            line_str = line.strip()
            if "STRESS" in line_str.upper() or line_str.startswith("-4  STRESS"):
                in_stress_block = True
                continue
            if not in_stress_block:
                continue
            if line_str.startswith("-3") or line_str.startswith("-1"):
                in_stress_block = False
                continue
            parsed = self._parse_single_stress_line(line_str)
            if parsed is not None:
                n_id, vm = parsed
                results[n_id] = vm
        return results

    def parse_full_results(self, result_text: str) -> Dict[int, FeaNodalResult]:
        """
        Extrait simultanément les déplacements et les contraintes nodales
        et retourne un dictionnaire de FeaNodalResult indexé par ID de nœud.
        """
        disps = self.parse_nodal_displacements(result_text)
        stresses = self.parse_nodal_stresses(result_text)
        all_ids = set(disps.keys()) | set(stresses.keys())

        results: Dict[int, FeaNodalResult] = {}
        for nid in sorted(all_ids):
            disp = disps.get(nid, Vector3D(0.0, 0.0, 0.0))
            stress = stresses.get(nid, 0.0)
            results[nid] = FeaNodalResult(
                node_id=nid,
                displacement=disp,
                von_mises_stress_mpa=stress
            )
        return results


